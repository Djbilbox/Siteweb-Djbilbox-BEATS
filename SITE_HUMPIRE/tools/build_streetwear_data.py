"""Build assets/js/streetwear-data.js from the Fourthwall store.

Run again after adding products on Fourthwall:  python tools/build_streetwear_data.py
Season placement comes from the product type (COLLECTIONS below);
put a product slug in OVERRIDE to move it by hand.
"""
import html, json, os, re, subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
STORE = 'https://djbilbox-beats-shop.fourthwall.com/en-eur'
PLAYLIST = 'PLC62DpPjARlo'          # YouTube "STREETWEAR HUMPIRE"

TYPES = [('tee', r't-shirt|\btee\b'), ('pull', r'\bpull\b|sweater|crewneck'), ('hoodie', r'hoodie|sweat'),
         ('bottom', r'jogger|jogging|pant'), ('neck', r'balaclava|cagoule|neck'), ('cap', r'\bcap\b|bucket|hat'),
         ('goodies', r'mug|tote|sticker|poster')]
COLLECTIONS = {'tee': 'summer', 'cap': 'summer', 'hoodie': 'autumn', 'bottom': 'autumn',
               'pull': 'winter', 'neck': 'winter', 'goodies': 'goodies'}
OVERRIDE = {}
TYPE_OVERRIDE = {'humpire-corporation-iron-riot': 'tee', 'humpire-corporation-neon-graveyard': 'tee'}
VIDEO = {  # promo video per product (YouTube id); others are matched by name
    'humpire-oversized-tee-spray-black': 'JO8DL2QH8Qk', 'humpire-oversized-tee-spray-white': 'XeUwHoKLOIo',
    'humpire-hoodie-spray-black': 'DbjpP5J1rEQ', 'humpire-spray-bucket-hat': 'Sc0J0LB-slo',
    'humpire-spray-cap': 'aO01xo6Z168', 'rapforce38-t-shirt-logo-noir': '5TA-vq3TjK8',
    'rapforce38-t-shirt-texte-noir': 'cHCXZXpvz3k', 'humpire-corporation-iron-riot': 'lxvPOPGPagk',
    'humpire-corporation-neon-graveyard': 'cWoQ9f-yDb8', 'pull-humpire-corporation-collection': 'tb2YhcoYA0g',
    'balaclava-humpire-corporation': 'SaifCaeeaeo', 'humpire-corporation-iron-riot-hoodie': 'G1I7WRdEtgY',
    'humpire-corporation-iron-riot-premium-hoodie': 'Dbeqwf04YO8', 'humpire-corporation-loud-or-die-hoodie': '4USAB9ao6fI',
    'humpire-corporation-neon-graveyard-hoodie': 'i-Gl0F4QXEM', 'humpire-zombies-neon-horror-t-shirt': 'UcUB5xB_g0A'}

def get(url):
    return subprocess.run(['curl', '-sL', '--compressed', '-A', 'Mozilla/5.0', url],
                          capture_output=True, timeout=60).stdout.decode('utf-8', 'ignore')

def meta(page, prop):
    m = re.search(r'<meta property="%s" content="([^"]*)"' % re.escape(prop), page)
    return html.unescape(m.group(1)) if m else ''

def words(s):
    return set(w for w in re.findall(r'[a-z0-9]+', s.lower()) if len(w) > 2) - {
        'humpire', 'the', 'and', 'corporation', 'by', 'oversized', 'djbilbox', 'beats', 'black', 'noir', 'white', 'shop', 'official'}

def main():
    listing = get(STORE + '/collections/all')
    slugs = sorted(set(re.findall(r'/products/([a-z0-9-]+)', listing)) - {'collections'})
    vids = json.load(open(os.path.join(HERE, 'youtube_playlists.json'), encoding='utf-8')).get(PLAYLIST, {}).get('videos', [])
    items = []
    for s in slugs:
        p = get(STORE + '/products/' + s)
        name = meta(p, 'og:title')
        if not name:
            continue
        kind = TYPE_OVERRIDE.get(s) or next((k for k, rx in TYPES if re.search(rx, name + ' ' + s, re.I)), 'goodies')
        brand = 'RAPFORCE38' if 'rapforce' in s else 'NK-VISIONS' if 'nk-visions' in s else 'HUMPIRE'
        w = words(name)
        best = max(vids, key=lambda v: len(w & words(v[1])), default=None)
        video = VIDEO.get(s) or (best[0] if best and len(w & words(best[1])) >= 2 else '')
        items.append({'slug': s, 'name': name, 'brand': brand, 'type': kind,
                      'season': OVERRIDE.get(s, COLLECTIONS[kind]),
                      'price': float(meta(p, 'og:price:amount') or 0),
                      'img': meta(p, 'og:image'),  # signed URL: keep it untouched
                      'desc': meta(p, 'og:description'), 'video': video,
                      'url': STORE + '/products/' + s})
    out = os.path.join(HERE, '..', 'assets', 'js', 'streetwear-data.js')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* Generated by tools/build_streetwear_data.py from the Fourthwall store — do not edit. */\n')
        f.write('window.SW_STORE = %s;\n' % json.dumps(STORE))
        f.write('window.SW_ITEMS = %s;\n' % json.dumps(items, ensure_ascii=False, indent=0))
    from collections import Counter
    print(len(items), dict(Counter(i['season'] for i in items)), sum(1 for i in items if i['video']), 'with video')
    for i in items: print(' ', i['season'], i['type'], i['price'], i['name'], i['video'])

main()
