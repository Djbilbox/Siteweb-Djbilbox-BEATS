"""Build assets/js/beats-data.js from the YouTube instrumental playlist.

Refresh: python tools/youtube_playlists.py tools/youtube_playlists.json
then:    python tools/build_beats_data.py
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ALL_BEATS = 'PLbtcZhy947NUG4ukai3ZNcw3Gvz5dd8Th'

GENRES = [  # first match wins
    ('Oriental', r'oriental|arab|maghreb|\bdz\b|chaabi|ra[iï]\b|balkan|turk|istanbul|beyrouth'),
    ('G-Funk', r'g-?funk|west ?coast'),
    ('Afro', r'afro|dancehall|reggaeton|kompa|coup[ée] d[ée]cal'),
    ('Drill', r'drill'),
    ('House & Club', r'house|d&b|dnb|drum ?(and|&|n) ?bass|club|electro|disco'),
    ('Trap', r'trap'),
]

def parse(vid, title):
    t = title.strip()
    if not re.search(r'beat|instru', t, re.I):
        return None
    free = bool(re.search(r'\[free\]|\(free\)', t, re.I))
    clean = re.sub(r'\[free\]|\(free\)', '', t, flags=re.I).strip(' "“”')
    clean = re.sub(r'^(djbilbox|dibilbox)\s*-\s*', '', clean, flags=re.I)
    name = re.split(r'\s[|–—-]\s|\s\(|\s\||"\s', clean)[0].strip(' "“”|-')
    name = re.sub(r'\s*\(.*$', '', name).strip()
    if not name or len(name) > 34:
        name = clean[:34].strip()
    bpm = re.search(r'(\d{2,3})\s?BPM', t, re.I)
    key = re.search(r'\(\s*([A-G][b#]?\s?(?:minor|major|min|maj|m))\s*\)', t, re.I)
    artists = re.search(r'([A-Z0-9][\w.\' ]+ x [\w.\' ]+?) Type Beat', t)
    genre = next((g for g, rx in GENRES if re.search(rx, t, re.I)), 'Hip-Hop')
    return {'id': vid, 'name': name.upper(), 'type': artists.group(1).strip() if artists else '',
            'genre': genre, 'bpm': int(bpm.group(1)) if bpm else None,
            'key': key.group(1).replace(' ', '') if key else '', 'free': free}

def main():
    data = json.load(open(os.path.join(HERE, 'youtube_playlists.json'), encoding='utf-8'))
    seen, beats = set(), []
    for vid, title in data[ALL_BEATS]['videos']:
        b = parse(vid, title)
        if b and vid not in seen:
            seen.add(vid); beats.append(b)
    out = os.path.join(HERE, '..', 'assets', 'js', 'beats-data.js')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* Generated by tools/build_beats_data.py from the YouTube playlist "All Beats" — do not edit. */\n')
        f.write('window.BEATS_PLAYLIST = %s;\n' % json.dumps(ALL_BEATS))
        f.write('window.BEATS = %s;\n' % json.dumps(beats, ensure_ascii=False, separators=(',', ':')))
    from collections import Counter
    print(len(beats), 'beats', dict(Counter(b['genre'] for b in beats)), sum(b['free'] for b in beats), 'free')

main()
