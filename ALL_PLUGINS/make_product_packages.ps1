# =============================================================================
#  DJBILBOX BEATS - one installer + one ZIP per product (for Gumroad delivery)
#  Input : <Stage>\synths|loadout|orbit\*.vst3   (+ <Stage>\docs\*)
#  Output: <Out>\packages\<slug>.zip  (Setup.exe + README.txt + EULA + notices + manual PDF when available)
#          plus bundle packages: humpire-loadout, humpire-orbit, djbilbox-beats-synth-collection
#  HUMPIRE CHAABI ORCHESTRA is packaged as its own product (it plays its built-in modelled instruments).
# =============================================================================
param(
    [Parameter(Mandatory = $true)][string]$Stage,
    [Parameter(Mandatory = $true)][string]$Out,
    [string]$Version = "1.0.0",
    [string]$Iscc = "C:\Program Files (x86)\Inno Setup 6\ISCC.exe"
)
$ErrorActionPreference = "Stop"
$Stage = (Resolve-Path $Stage).Path
New-Item -ItemType Directory -Force -Path $Out | Out-Null
$Out = (Resolve-Path $Out).Path
$Docs = Join-Path $Stage "docs"
$Eula = Join-Path $Docs "EULA_DJBILBOX_BEATS.txt"
$Notices = Join-Path $Docs "THIRD_PARTY_NOTICES.txt"
if (-not (Test-Path $Eula)) { throw "EULA missing: $Eula" }

$IssDir = Join-Path $Out "iss"
$SetupDir = Join-Path $Out "setups"
$PkgDir = Join-Path $Out "packages"
foreach ($d in @($IssDir, $SetupDir, $PkgDir)) { New-Item -ItemType Directory -Force -Path $d | Out-Null }

function Get-Slug([string]$text) {
    return (($text.ToLower() -replace '[^a-z0-9]+', '-').Trim('-'))
}

function Get-AppGuid([string]$slug) {
    $md5 = [System.Security.Cryptography.MD5]::Create()
    $hash = $md5.ComputeHash([System.Text.Encoding]::UTF8.GetBytes("djbilbox-" + $slug))
    return ([guid]::new($hash)).ToString().ToUpper()
}

# ---- collect bundles
$all = New-Object System.Collections.Generic.List[object]
foreach ($g in @("synths", "loadout", "orbit", "chaabi")) {
    $dir = Join-Path $Stage $g
    if (-not (Test-Path $dir)) { continue }
    foreach ($b in (Get-ChildItem -Path $dir -Directory -Filter "*.vst3" | Sort-Object Name)) {
        $name = $b.Name -replace '\.vst3$', ''
        $all.Add([pscustomobject]@{ Group = $g; Dir = $b.FullName; BundleName = $b.Name; Name = $name; Slug = (Get-Slug $name) })
    }
}
if ($all.Count -eq 0) { throw "No VST3 found in $Stage" }

$report = New-Object System.Collections.Generic.List[string]

function New-Package {
    param([string]$AppName, [string]$Slug, [object[]]$Items, [string]$Blurb)

    $guid = Get-AppGuid $Slug
    $lines = New-Object System.Collections.Generic.List[string]
    foreach ($it in $Items) {
        $lines.Add("Source: ""$($it.Dir)\*""; DestDir: ""{commoncf64}\VST3\$($it.BundleName)""; Flags: recursesubdirs createallsubdirs ignoreversion")
    }
    if (Test-Path $Docs) {
        $lines.Add("Source: ""$Eula""; DestDir: ""{commonpf64}\DJBILBOX BEATS\Documentation""; Flags: ignoreversion")
        if (Test-Path $Notices) { $lines.Add("Source: ""$Notices""; DestDir: ""{commonpf64}\DJBILBOX BEATS\Documentation""; Flags: ignoreversion") }
        $manual = Join-Path $Docs "manuals\$Slug.pdf"
        if (Test-Path $manual) { $lines.Add("Source: ""$manual""; DestDir: ""{commonpf64}\DJBILBOX BEATS\Documentation""; Flags: ignoreversion") }
    }

    $iss = @"
; Generated by ALL_PLUGINS/make_product_packages.ps1 - do not edit
[Setup]
AppId={{$guid}
AppName=$AppName
AppVersion=$Version
AppPublisher=DJBILBOX BEATS / HUMPIRE
DefaultDirName={commonpf64}\DJBILBOX BEATS\$Slug
DisableDirPage=yes
DisableProgramGroupPage=yes
PrivilegesRequired=admin
ArchitecturesAllowed=x64compatible
ArchitecturesInstallIn64BitMode=x64compatible
OutputDir=$SetupDir
OutputBaseFilename=$Slug-setup
Compression=lzma2/max
SolidCompression=yes
WizardStyle=modern
LicenseFile=$Eula
UninstallDisplayName=$AppName

[Languages]
Name: "en"; MessagesFile: "compiler:Default.isl"

[Files]
$($lines -join "`r`n")
"@
    $issPath = Join-Path $IssDir "$Slug.iss"
    [System.IO.File]::WriteAllText($issPath, $iss, (New-Object System.Text.UTF8Encoding($true)))
    & $Iscc "/Q" $issPath
    if ($LASTEXITCODE -ne 0) { throw "ISCC failed for $Slug ($LASTEXITCODE)" }

    # ---- zip: setup + docs
    $work = Join-Path $Out "work\$Slug"
    if (Test-Path $work) { Remove-Item -Recurse -Force $work }
    New-Item -ItemType Directory -Force -Path $work | Out-Null
    Copy-Item (Join-Path $SetupDir "$Slug-setup.exe") $work
    Copy-Item $Eula $work
    if (Test-Path $Notices) { Copy-Item $Notices $work }
    $manual = Join-Path $Docs "manuals\$Slug.pdf"
    if (Test-Path $manual) { Copy-Item $manual $work }
    $readme = @"
$AppName  -  version $Version
$Blurb

INSTALL
1. Close your DAW (FL Studio, Ableton Live, Reaper...).
2. Run $Slug-setup.exe and accept the administrator prompt.
   If Windows SmartScreen shows "Windows protected your PC", click "More info" then "Run anyway".
3. Plugins are installed in C:\Program Files\Common Files\VST3
4. FL Studio: Options > Manage plugins > Find installed plugins.

LICENSE
Everything you create with this plugin is yours and royalty-free.
Read EULA_DJBILBOX_BEATS.txt for the full terms.

SUPPORT: djbilboxbeats.com
"@
    [System.IO.File]::WriteAllText((Join-Path $work "README.txt"), $readme, (New-Object System.Text.UTF8Encoding($true)))
    $zip = Join-Path $PkgDir "$Slug.zip"
    if (Test-Path $zip) { Remove-Item -Force $zip }
    Compress-Archive -Path (Join-Path $work "*") -DestinationPath $zip -CompressionLevel Optimal
    $report.Add("$Slug.zip  ($AppName, $($Items.Count) plugin(s))")
    Write-Host "OK  $Slug"
}

# ---- single products
foreach ($it in $all) {
    try { New-Package -AppName $it.Name -Slug $it.Slug -Items @($it) -Blurb "VST3 plugin by DJBILBOX BEATS." }
    catch { Write-Host "FAILED $($it.Slug): $_"; $report.Add("FAILED $($it.Slug): $_") }
}

# ---- bundles
$bundles = @(
    @{ Name = "HUMPIRE LOADOUT"; Slug = "humpire-loadout"; Group = "loadout"; Blurb = "Eight studio effects: EQ, compressor, enhancer, limiter, reverb, delay, lo-fi and performance FX." },
    @{ Name = "HUMPIRE ORBIT"; Slug = "humpire-orbit"; Group = "orbit"; Blurb = "Vocal effects bundle: pitch correction, harmonies, doubling and more." },
    @{ Name = "DJBILBOX BEATS Synth Collection"; Slug = "djbilbox-beats-synth-collection"; Group = "synths"; Blurb = "The complete DJBILBOX BEATS synthesizer collection." },
    @{ Name = "DJBILBOX BEATS Complete Collection"; Slug = "djbilbox-beats-complete-collection"; Group = "all"; Blurb = "Every DJBILBOX BEATS and HUMPIRE plugin of this release." }
)
foreach ($b in $bundles) {
    if ($b.Group -eq "all") { $items = @($all) } else { $items = @($all | Where-Object { $_.Group -eq $b.Group }) }
    if ($items.Count -gt 1) {
        try { New-Package -AppName $b.Name -Slug $b.Slug -Items $items -Blurb $b.Blurb }
        catch { Write-Host "FAILED $($b.Slug): $_"; $report.Add("FAILED $($b.Slug): $_") }
    }
}

[System.IO.File]::WriteAllLines((Join-Path $Out "packages_report.txt"), $report)
Write-Host ($report -join "`n")
