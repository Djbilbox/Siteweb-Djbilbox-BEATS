"""Generates Source/Generated/GFunkSpec.h and .cpp from gfunk_spec + gen_presets."""
import os

import gfunk_spec as S
import gen_presets as P
import gfunk_skins as K

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Source", "Generated")
os.makedirs(OUT, exist_ok=True)


def f(x):
    return repr(float(x)) + "f"


def rect(r):
    return "{ %d, %d, %d, %d }" % r


NAMES = {"HEADER_RECT": "headerRect", "LCD_RECT": "lcdRect", "METER_RECT": "meterRect", "SCREEN_RECT": "screenRect", "SCREEN_INNER": "screenInnerRect", "TABS_RECT": "tabsRect", "KEYS_RECT": "keysRect", "KEYBOARD_RECT": "keyboardRect", "WHEELS_RECT": "wheelsRect", "HERO_RECT": "heroRect"}


FREE_PER_CAT = 10


def main():
    presets = P.make_presets()
    n = len(S.PARAMS)
    items = S.layout_items()

    h = ["// GENERATED by tools/gen_code.py - do not edit.", "#pragma once", "namespace GFunkSpec", "{",
         "enum ParamIndex", "{"]
    for p in S.PARAMS:
        h.append(f"    P_{p[0]},")
    h += ["    NumParams", "};", "",
          "enum ParamType { TypeFloat = 0, TypeInt = 1, TypeChoice = 2 };",
          "struct ParamDef { const char* id; const char* label; int type; float minV, maxV, defV, skew; const char* fmt; const char* choices; };",
          "extern const ParamDef params[NumParams];", "",
          "struct UiItem { int param; int kind; int lx, ly, lw, lh; int x, y, w, h; };  // kind 0 = knob, 1 = combo",
          f"constexpr int numUiItems = {len(items)};", "extern const UiItem uiItems[numUiItems];", "",
          "struct Rect { int x, y, w, h; };",
          f"constexpr int windowW = {S.W}, windowH = {S.H};"]
    for nm in ["HEADER_RECT", "LCD_RECT", "METER_RECT", "SCREEN_RECT", "SCREEN_INNER", "TABS_RECT", "KEYS_RECT",
               "KEYBOARD_RECT", "WHEELS_RECT", "HERO_RECT"]:
        h.append(f"constexpr Rect {NAMES[nm]} = {rect(getattr(S, nm))};")
    h.append("constexpr int numPanels = %d;" % len(S.PANELS))
    h.append("constexpr Rect panelRects[numPanels] = { %s };" % ", ".join(rect(pn[2]) for pn in S.PANELS))
    h.append(f"constexpr int btnY = {S.BTN_Y}, btnH = {S.BTN_H};")
    h.append("constexpr int btnX[%d] = { %s };" % (len(S.BTN_X), ", ".join(str(x) for x in S.BTN_X)))
    free_cnt = FREE_PER_CAT * len(P.CATEGORIES)
    h += ["", "#ifdef GFUNK_FREE   // GFUNK 2027 Free: %d presets (every %dth preset of each category)" % (free_cnt, P.PER_CAT // FREE_PER_CAT),
          f"constexpr int numPresets = {free_cnt};", f"constexpr int presetsPerCategory = {FREE_PER_CAT};",
          "#else", f"constexpr int numPresets = {len(presets)};", f"constexpr int presetsPerCategory = {P.PER_CAT};", "#endif",
          f"constexpr int numCategories = {len(P.CATEGORIES)};", "extern const char* const categoryNames[numCategories];",
          "struct PresetInfo { const char* name; int category; };",
          "extern const PresetInfo presetInfo[numPresets];",
          "extern const float presetValues[numPresets][NumParams];",
          "struct SkinDef { const char* name; unsigned label, tick, ring, pointer, comboTop, comboBot, comboLine, keyWTop, keyWBot, keyBTop, keyBBot; };",
          f"constexpr int numSkins = {len(K.SKINS)};", "extern const SkinDef skins[numSkins];", "}", ""]
    with open(os.path.join(OUT, "GFunkSpec.h"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(h))

    c = ["// GENERATED by tools/gen_code.py - do not edit.", '#include "GFunkSpec.h"', "namespace GFunkSpec", "{",
         "const ParamDef params[NumParams] = {"]
    for p in S.PARAMS:
        typ = {"f": "TypeFloat", "i": "TypeInt", "c": "TypeChoice"}[p[2]]
        c.append('    { "%s", "%s", %s, %s, %s, %s, %s, "%s", "%s" },' %
                 (p[0], p[1], typ, f(p[3]), f(p[4]), f(p[5]), f(p[6]), p[7], p[8]))
    c += ["};", "", f"const UiItem uiItems[numUiItems] = {{"]
    for it in items:
        c.append("    { P_%s, %d, %d, %d, %d, %d, %d, %d, %d, %d }," % (
            it["id"], 0 if it["kind"] == "knob" else 1, it["lx"], it["ly"], it["lw"], it["lh"],
            it["x"], it["y"], it["w"], it["h"]))
    c += ["};", "", "const char* const categoryNames[numCategories] = {"]
    for name in P.CATEGORIES:
        c.append(f'    "{name}",')
    step = P.PER_CAT // FREE_PER_CAT
    free = [pr for k, pr in enumerate(presets) if (k % P.PER_CAT) % step == 0 and (k % P.PER_CAT) // step < FREE_PER_CAT]
    for tag, lst in (("#ifdef GFUNK_FREE", free), ("#else", presets)):
        if tag.startswith("#ifdef"):
            c.append("};")
        c += [tag, "", "const PresetInfo presetInfo[numPresets] = {"]
        for name, cat, _ in lst:
            c.append('    { "%s", %d },' % (name.replace('"', "'"), cat))
        c += ["};", "", "const float presetValues[numPresets][NumParams] = {"]
        for _, _, vals in lst:
            c.append("    { " + ", ".join(f(v) for v in vals) + " },")
        c.append("};")
    c += ["#endif", "", "const SkinDef skins[numSkins] = {"]
    for sk in K.SKINS:
        cols = ", ".join("0x" + sk[k] for k in ["label", "tick", "ring", "pointer", "combo_top", "combo_bot", "combo_line", "key_w_top", "key_w_bot", "key_b_top", "key_b_bot"])
        c.append('    { "%s", %s },' % (sk["name"], cols))
    c += ["};", "}", ""]
    with open(os.path.join(OUT, "GFunkSpec.cpp"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(c))
    print("params", n, "ui items", len(items), "presets", len(presets))


if __name__ == "__main__":
    main()

