"""Real flute for the Hippie Flute engine: VSCO 2 Community Edition, Woodwinds/Flute (CC0, github.com/sgossner/VSCO-2-CE),
sustained notes with vibrato (susvib) and without (susNV, soft v1 / loud v3).
Each note: cut at the attack, exact pitch measured, a crossfaded sustain loop baked in its steady middle, level
matched, mono 44.1 kHz, 16-bit FLAC -> Assets/flute/*.flac, and Source/FluteMap.h (root key, tuning, loop).
usage: python -E -P make_flute.py <VSCO-2-CE/Woodwinds/Flute folder>"""
import os, re, sys
import numpy as np
import soundfile as sf
import librosa

SRC = sys.argv[1]
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'Assets', 'flute')
os.makedirs(OUT, exist_ok=True)
for f in os.listdir(OUT): os.remove(os.path.join(OUT, f))
SR = 44100

def loop(x, f0):
    """Crossfaded loop in the steady middle of the note: returns audio cut at the loop end, loop start, loop end."""
    n = len(x); period = SR / f0
    a0 = min(int(0.9 * SR), int(0.35 * n)); a1 = min(int(0.85 * n), a0 + int(1.4 * SR))   # attack, then a 1.4 s loop
    def zc(i):
        for k in range(i, min(n - 1, i + int(2 * period) + 2)):
            if x[k] <= 0 < x[k + 1]: return k + 1
        return i
    ls = zc(a0)
    le = zc(min(n - 2, ls + int(round((a1 - ls) / period)) * int(round(period))))
    xf = int(min(0.15 * SR, (le - ls) * 0.4))
    y = x[:le].copy()
    w = np.sin(np.linspace(0, np.pi / 2, xf)) ** 2
    y[le - xf:le] = x[le - xf:le] * (1 - w) + x[ls - xf:ls] * w
    return y, ls, le

rows = []
for layer, folder, pat in (('vib', 'susvib', r'_susvib_([A-G]#?\d)_v1_(\d)'), ('nv', 'susNV', r'_susNV_([A-G]#?\d)_v(\d)_1')):
    for fn in sorted(os.listdir(os.path.join(SRC, folder))):
        m = re.search(pat, fn)
        if not m: continue
        x, sr = sf.read(os.path.join(SRC, folder, fn), dtype='float32', always_2d=True)
        x = x.mean(axis=1)
        if sr != SR: x = librosa.resample(x, orig_sr=sr, target_sr=SR)
        pk = np.abs(x).max(); i0 = int(np.argmax(np.abs(x) > 0.02 * pk)); x = x[max(0, i0 - int(0.004 * SR)):]
        fi = int(0.004 * SR); x[:fi] *= np.linspace(0, 1, fi)
        seg = x[int(0.3 * SR):int(min(len(x), 1.6 * SR))]
        f0, v, _ = librosa.pyin(seg, fmin=200, fmax=2600, sr=SR, frame_length=2048, hop_length=256, resolution=0.01)
        f0 = f0[~np.isnan(f0)]
        midi = float(np.median(librosa.hz_to_midi(f0)))
        key = int(round(midi)); cents = (midi - key) * 100
        y, ls, le = loop(x, librosa.midi_to_hz(midi))
        sus = y[int(0.3 * SR):]
        y = y * (10 ** (-16 / 20) / (np.sqrt(np.mean(sus ** 2)) + 1e-9))
        y = np.clip(y, -0.99, 0.99)
        vel = 1 if layer == 'vib' else int(m.group(2))
        name = 'flute_%s_%d_v%d.flac' % (layer, key, vel)
        if os.path.exists(os.path.join(OUT, name)): name = name.replace('.flac', 'b.flac')
        sf.write(os.path.join(OUT, name), y.astype(np.float32), SR, subtype='PCM_16')
        rows.append((name, layer, key, cents, vel, ls, le, len(y)))
        print('%-28s %-4s key %3d %+5.1f c  v%d  loop %6d-%6d  len %.2f s' % (name, layer, key, cents, vel, ls, le, len(y) / SR))

L = ['// Generated by Tools/make_flute.py: the real flute of the Hippie Flute engine (VSCO 2 CE, CC0).',
     '#pragma once', '', 'namespace Cz', '{',
     'struct FluteNote { const char* resource; bool vibrato; int key; float cents; int velocityLayer; int loopStart, loopEnd, length; };',
     'inline constexpr FluteNote fluteNotes[] = {']
for name, layer, key, cents, vel, ls, le, n in rows:
    res = re.sub(r'[^A-Za-z0-9]', '_', name)
    L.append('    { "%s", %s, %d, %.1ff, %d, %d, %d, %d },' % (res, 'true' if layer == 'vib' else 'false', key, cents, vel, ls, le, n))
L += ['};', '}', '']
open(os.path.join(HERE, '..', 'Source', 'FluteMap.h'), 'w', newline='\n').write('\n'.join(L))
print(len(rows), 'notes, %.1f MB' % (sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT)) / 1e6))
