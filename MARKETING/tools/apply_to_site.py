#!/usr/bin/env python3
"""Add the new products to the website source (djbilboxbeats.github.io: assets/js/vst-data.js + products-data.js + img/products/).

Usage: python3 tools/apply_to_site.py <site_repo_dir> [--dry]
Products without a Gumroad slug (MARKETING/slugs.json) are shown as "Coming soon" (price "SOON") so no dead buy button is published.
"""
import json, os, re, shutil, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
site = sys.argv[1]; dry = '--dry' in sys.argv
load = lambda p: json.load(open(p, encoding='utf-8'))
pricing = load(os.path.join(ROOT, 'pricing.json'))
slugs = load(os.path.join(ROOT, 'slugs.json')) if os.path.exists(os.path.join(ROOT, 'slugs.json')) else {}
fiches = [load(os.path.join(ROOT, 'fiches', n)) for n in sorted(os.listdir(os.path.join(ROOT, 'fiches'))) if n.endswith('.json') and not n.startswith('_')]
fiches = [f for f in fiches if f['id'] not in pricing.get('not_for_sale_yet', {})]
js = lambda o: json.dumps(o, ensure_ascii=False, indent=2)

def price_of(f):
    if f['id'] in pricing.get('overrides', {}): return pricing['overrides'][f['id']]
    return pricing['defaults']['synth' if f['category'] == 'instrument' else 'effect']

def entries():
    vsts, prods = [], {}
    by_group = {}
    for f in fiches: by_group.setdefault(f['group'], []).append(f)
    items = [(f, price_of(f), slugs.get(f['id'], ''), f['category'], f['tagline'], f.get('about', []), f.get('features', []), f.get('specs', []), f.get('includes', []), f.get('genres', [])) for f in fiches]
    for b in pricing['bundles']:
        members = by_group.get(b['members_group'], [])
        if not members: continue
        total = sum(price_of(m) for m in members)
        fb = {"id": b['id'], "name": b['name'], "kind": b['kind'], "sub": f"{len(members)} VST3 plugins, one payment", "tagline": b['tagline'], "accent": "#f5b544"}
        about = [b['tagline'], f"Bought separately these {len(members)} plugins cost ${total}. The bundle is ${b['price']}."]
        feats = [{"icon": "fa-puzzle-piece", "t": m['name'], "d": m['tagline']} for m in members]
        items.append((fb, b['price'], slugs.get(b['id'], ''), 'instrument' if b['members_group'] == 'synths' else 'effect', b['tagline'], about, feats,
                      [{"k": "Format", "v": "VST3 64-bit (Windows)"}, {"k": "Plugins", "v": str(len(members))}], [f"{len(members)} VST3 plugins", "Windows installer", "PDF manuals", "Royalty-free license"], []))
    for f, price, slug, cat, tagline, about, feats, specs, includes, genres in items:
        pid = f['id']; soon = not slug
        pr = "SOON" if soon else str(price)
        vsts.append({"id": pid, "name": f"{f['name']} — {f.get('kind', '')} VST3 Plugin".strip(' —'), "img": f"img/products/{pid}-thumb.jpg", "category": cat,
                     "tags": [x for x in ([f.get('kind', '')] + [f.get('badges', [''])[0] if f.get('badges') else ''] + ['VST3 · Win x64']) if x][:3],
                     "tier": "bundle" if pid in [b['id'] for b in pricing['bundles']] else "pro", "price": pr, "badge": "🆕 New", "buy": slug, "demo": "",
                     "note": f.get('tagline', tagline)[:110]})
        prods[pid] = {"type": "vst", "name": f['name'], "sub": f.get('sub', ''), "tagline": tagline, "cover": f"img/products/{pid}-cover.jpg",
                      "accent": f.get('accent', '#f5b544'), "accent2": "#8a5cff", "tier": "pro", "price": pr, "code": "", "note": f.get('tagline', '')[:80],
                      "buy": slug, "demo": "", "tags": (genres or f.get('tags', []))[:6], "about": about, "features": feats,
                      "specs": specs + [{"k": "Platform", "v": "Windows 10/11, 64-bit"}, {"k": "License", "v": "Royalty-free for your productions"}],
                      "includes": includes}
    return vsts, prods

vsts, prods = entries()
vp = os.path.join(site, 'assets/js/vst-data.js'); pp = os.path.join(site, 'assets/js/products-data.js')
vt = open(vp, encoding='utf-8').read(); pt = open(pp, encoding='utf-8').read()
new_v = [v for v in vsts if f'id:"{v["id"]}"' not in vt and f'"id": "{v["id"]}"' not in vt]
new_p = {k: v for k, v in prods.items() if not re.search(r'"%s"\s*:\s*\{' % re.escape(k), pt)}
print('new VSTS:', len(new_v), ' new PRODUCTS:', len(new_p))
if not dry:
    vblock = "\n  /* ========== NEW: DJBILBOX BEATS / HUMPIRE plugins (October 2026) — generated by MARKETING/tools/apply_to_site.py ========== */\n" + ",\n".join("  " + js(v).replace("\n", "\n  ") for v in new_v) + ",\n"
    pblock = "\n  /* ========== NEW: plugins (October 2026) ========== */\n" + ",\n".join("  " + json.dumps(k) + ": " + js(v).replace("\n", "\n  ") for k, v in new_p.items()) + ",\n"
    vt = vt.replace('window.VSTS = [', 'window.VSTS = [' + vblock, 1); pt = pt.replace('window.PRODUCTS = {', 'window.PRODUCTS = {' + pblock, 1)
    open(vp, 'w', encoding='utf-8').write(vt); open(pp, 'w', encoding='utf-8').write(pt)
    os.makedirs(os.path.join(site, 'img/products'), exist_ok=True)
    for f in fiches + [{'id': b['id']} for b in pricing['bundles']]:
        for kind in ('thumb', 'cover'):
            src = os.path.join(ROOT, 'out', f"{f['id']}-{kind}.jpg")
            if os.path.exists(src): shutil.copy(src, os.path.join(site, 'img/products', f"{f['id']}-{kind}.jpg"))
    # syntax check both files in node
    chk = "global.window={};for(const f of process.argv.slice(1)){new Function(require('fs').readFileSync(f,'utf8'))();}console.log('JS OK',window.VSTS.length,Object.keys(window.PRODUCTS).length)"
    subprocess.check_call(['node', '-e', chk, vp, pp])
