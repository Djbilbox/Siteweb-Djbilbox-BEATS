"""Prepares the photo-real DZPOWER faceplate (rendered with Google Flow / Nano Banana from the old interface, same
layout) for the plug-in:
  - erases the white tick Flow left on top of every knob cap (the plug-in draws a lit index that turns),
  - measures where the knob caps, the speaker-grille holes, the LED dots beside the faders and the cassette
    reels really are in the image,
  - writes Assets/faceplate.jpg (2000 px wide) and Source/FaceplateLayout.h (those positions, panel pixels).
usage: python -E -P faceplate_layout.py <rendered faceplate image (2400 px wide)>"""
import os, sys
import numpy as np
from PIL import Image
from scipy import ndimage as nd

HERE = os.path.dirname(os.path.abspath(__file__))
im = np.asarray(Image.open(sys.argv[1]).convert('RGB')).astype(np.float32)
S = im.shape[1] / 1000.0                     # image pixels per panel pixel
lum = im.mean(axis=2)
mag = np.hypot(nd.sobel(nd.gaussian_filter(lum, 1.5), 1), nd.sobel(nd.gaussian_filter(lum, 1.5), 0))
th = np.linspace(0, 2 * np.pi, 72, endpoint=False)

# knob caps: start from the old layout (mock-up units, half = panel pixels), best circle of strong edges nearby
KNOBS = [('rate', 258, 648, 0), ('amount', 413, 648, 0), ('pitch', 567, 648, 0), ('volume', 1575, 395, 0), ('reverb', 1752, 395, 0),
         ('glide', 825, 865, 0), ('filter', 1068, 865, 0), ('resoK', 1222, 865, 0), ('chorus', 1387, 838, 0), ('dist', 1515, 838, 0),
         ('dtime', 1643, 860, 0), ('feedback', 1771, 860, 0), ('tone', 640, 365, 1), ('body', 740, 365, 1), ('bright', 640, 455, 1),
         ('width', 740, 455, 1), ('texture', 1262, 365, 1), ('fenvK', 1362, 365, 1), ('delay', 1312, 455, 1)]
caps = []
for name, mx, my, small in KNOBS:
    x, y = mx * 0.5 * S, my * 0.5 * S
    rs = np.arange(int((8 if small else 13) * S), int((15 if small else 24) * S))
    best = (-1, 0, 0, 0)
    for dy in range(-20, 21, 2):
        for dx in range(-20, 21, 2):
            cx, cy = x + dx, y + dy
            xs = (cx + np.outer(rs, np.cos(th))).astype(int); ys = (cy + np.outer(rs, np.sin(th))).astype(int)
            sc = mag[ys, xs].mean(axis=1); i = int(np.argmax(sc))
            if sc[i] > best[0]: best = (sc[i], cx, cy, rs[i])
    _, cx, cy, r = best
    caps.append((name, cx / S, cy / S, r / S))
    # the tick: a bright vertical line at the top of the cap -> each row across it is filled by interpolating
    # between the cap's own colour just left and right of it
    x0, x1 = int(cx - 0.16 * r), int(cx + 0.16 * r)
    for yy in range(int(cy - 0.92 * r), int(cy - 0.12 * r)):
        a, b = im[yy, x0 - 2], im[yy, x1 + 2]
        for xx in range(x0 - 1, x1 + 2):
            t = (xx - (x0 - 2)) / ((x1 + 2) - (x0 - 2))
            im[yy, xx] = a * (1 - t) + b * t

# dark round dots (grille holes, LED dots) inside a panel-pixel rectangle, away from the knob caps
def dots(x0, y0, x1, y1, darker=True):
    sub = lum[int(y0 * S):int(y1 * S), int(x0 * S):int(x1 * S)]
    local = nd.uniform_filter(sub, int(7 * S))
    m = (sub < local - 6) if darker else (sub > local + 6)
    m = nd.binary_opening(m, iterations=1)
    lab, n = nd.label(m)
    out = []
    for i, (sl, cnt) in enumerate(zip(nd.find_objects(lab), nd.sum(m, lab, range(1, n + 1)))):
        h, w = sl[0].stop - sl[0].start, sl[1].stop - sl[1].start
        if not (1.5 * S <= h <= 6 * S and 1.5 * S <= w <= 6 * S and cnt > 2 * S * S): continue
        cy, cx = nd.center_of_mass(m[sl])
        px, py = x0 + (sl[1].start + cx) / S, y0 + (sl[0].start + cy) / S
        if any((px - c[1]) ** 2 + (py - c[2]) ** 2 < (c[3] + 5) ** 2 for c in caps): continue
        # nor on the dark name plates under the small knobs
        if any(c[3] < 14 and abs(px - c[1]) < 21 and c[3] - 1 < py - c[2] < c[3] + 16 for c in caps): continue
        out.append((round(px, 1), round(py, 1)))
    return out

grilles = [dots(288, 152, 400, 260), dots(600, 152, 714, 260)]
FADERS = [('env0', 128.5), ('env1', 181), ('env2', 233.5), ('env3', 286.5), ('rsl0', 694), ('rsl1', 742.5), ('rsl2', 791.5), ('rsl3', 840), ('rsl4', 888)]
fader_y = {'env': (390, 480), 'rsl': (275, 355)}
# the slots themselves: the darkest column near each fader
slots = []
for name, fx in FADERS:
    y0, y1 = fader_y[name[:3]]
    band = lum[int(y0 * S):int(y1 * S), int((fx - 8) * S):int((fx + 8) * S)].mean(axis=0)
    slots.append((name, round(fx - 8 + (np.argmin(band) + 0.5) / S, 1)))
# cassette reels and the LED dots beside the faders follow the render's regular drawing; measured once on
# enlargements of this render (the dot finder above is not reliable on those small, half-lit dots)
reels = [(176.3, 101.7), (176.3, 180.8)]

Image.fromarray(np.clip(im, 0, 255).astype(np.uint8)).resize((2000, round(2000 * im.shape[0] / im.shape[1])), Image.LANCZOS) \
    .save(os.path.join(HERE, '..', 'Assets', 'faceplate.jpg'), quality=90, optimize=True)

L = ['// Generated by Tools/faceplate_layout.py from the rendered faceplate: where things really are, in panel pixels.',
     '#pragma once', '', 'namespace Face', '{', 'struct Cap { const char* name; float x, y, r; };',
     'inline constexpr Cap caps[] = {']
L += ['    { "%s", %.1ff, %.1ff, %.1ff },' % c for c in caps]
L += ['};', 'struct Dot { float x, y; };']
for i, g in enumerate(grilles):
    L += ['inline constexpr Dot grille%d[] = {' % i] + ['    { %.1ff, %.1ff },' % p for p in g] + ['};']
L += ['inline constexpr float slotX[] = { %s };   // env0..3, rsl0..4' % ', '.join('%.1ff' % s for _, s in slots)]
L += ['// beside every fader slot: two columns of 9 LED dots, 12.5 px left and right of the slot, from top to bottom',
      'inline constexpr float ledDx = 12.5f;', 'inline constexpr int ledRows = 9;',
      'inline constexpr float envLedTop = 400.4f, envLedBottom = 471.3f, rslLedTop = 284.6f, rslLedBottom = 338.3f;',
      'inline constexpr float reelR = 12.5f;']
L += ['inline constexpr Dot reels[] = { %s };' % ', '.join('{ %.1ff, %.1ff }' % r for r in reels), '}', '']
open(os.path.join(HERE, '..', 'Source', 'FaceplateLayout.h'), 'w', newline='\n').write('\n'.join(L))
print('caps', len(caps), 'grille holes', [len(g) for g in grilles], 'slots', slots)
